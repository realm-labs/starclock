#!/usr/bin/env node

import {
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { basename, dirname, resolve } from "node:path";

const arguments_ = process.argv.slice(2);
const check = arguments_.includes("--check");
const root = resolve(valueAfter("--root") ?? process.cwd());
const manifestRoot = resolve(
  root,
  "content-manifests/galactic-baseballer-v1",
);
const referenceRoot = resolve(
  root,
  "content-reference/galactic-baseballer-v1",
);
const configRoot = resolve(root, "config/galactic-baseballer");
const normalized = json(resolve(manifestRoot, "normalized-schema.json"));
const authoring = json(resolve(manifestRoot, "authoring-contract.json"));
const commonFields = normalized.common_envelope.required_fields
  .filter((field) => field !== "id");
const workbookByFile = new Map(authoring.workbooks.flatMap((workbook) =>
  workbook.normalized_files.map((file) => [file, workbook.file])));
const contractByFile = new Map(normalized.files.map((entry) =>
  [entry.file, entry]));

const groups = [
  {
    file: "profiles.toml",
    workbook: "GalacticBaseballerProfiles.xlsx",
  },
  {
    file: "arsenal.toml",
    workbook: "GalacticBaseballerArsenal.xlsx",
  },
  {
    file: "encounters.toml",
    workbook: "GalacticBaseballerEncounters.xlsx",
  },
  {
    file: "review.toml",
    workbook: "GalacticBaseballerReview.xlsx",
  },
];

const outputs = new Map();
for (const group of groups) {
  const workbook = authoring.workbooks.find(({ file }) =>
    file === group.workbook);
  if (!workbook) throw new Error(`workbook contract missing: ${group.workbook}`);
  const contracts = workbook.normalized_files.map((file) => {
    const contract = contractByFile.get(file);
    if (!contract) throw new Error(`normalized contract missing: ${file}`);
    return contract;
  });
  outputs.set(
    `schema/${group.file}`,
    renderSchema(group.file, contracts),
  );
}
outputs.set("project.toml", renderProject(groups.map(({ file }) => file)));

for (const [relative, contents] of [...outputs.entries()]
  .sort(([left], [right]) => left.localeCompare(right))) {
  const target = resolve(configRoot, relative);
  if (check) {
    if (!existsSync(target) || readFileSync(target, "utf8") !== contents) {
      throw new Error(`${relative}: generated Sora schema drift`);
    }
  } else {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, contents);
  }
}
console.log(
  `${check ? "Verified" : "Generated"} Goal 16 Sora project with `
  + `${normalized.files.length} isolated workbook tables.`,
);

function valueAfter(flag) {
  const index = arguments_.indexOf(flag);
  if (index < 0) return undefined;
  if (!arguments_[index + 1] || arguments_[index + 1].startsWith("--")) {
    throw new Error(`${flag} requires a value`);
  }
  return arguments_[index + 1];
}

function json(file) {
  return JSON.parse(readFileSync(file, "utf8"));
}

function pascal(value) {
  return value.replace(/\.json$/u, "").split(/[^a-zA-Z0-9]+/u)
    .filter(Boolean)
    .map((part) => `${part.slice(0, 1).toUpperCase()}${part.slice(1)}`)
    .join("");
}

function sheetName(file) {
  return pascal(file).slice(0, 31);
}

function quote(value) {
  return JSON.stringify(value);
}

function fieldsForRows(rows) {
  const discovered = new Set(rows.flatMap((row) => Object.keys(row)));
  discovered.delete("id");
  const fields = commonFields.filter((field) => discovered.has(field));
  const remaining = [...discovered]
    .filter((field) => !commonFields.includes(field))
    .sort();
  return [...fields, ...remaining];
}

function fieldIsOptional(rows, field) {
  return rows.some((row) =>
    !(field in row) || row[field] === "");
}

function renderProject(schemaFiles) {
  return `# @generated by generate-sora-schema.mjs; do not edit.
package = "starclock_galactic_baseballer_reference"
includes = [
${schemaFiles.map((file) => `  "schema/${file}",`).join("\n")}
]

[build]
default_source_format = "xlsx"
data_root = "data"
schema_lock = "../galactic-baseballer-generated/schema.lock"
excel_templates = "../galactic-baseballer-generated/templates"

[[build.codegen]]
target = "rust"
out = "../galactic-baseballer-generated/readers/rust"
format = "never"

[[build.exports]]
format = "binary"
out = "../galactic-baseballer-generated/config.sora"

[[build.exports]]
format = "json-debug"
out = "../galactic-baseballer-generated/debug-json"

[codegen.rust]
runtime_format = "sora"
`;
}

function renderSchema(fileName, contracts) {
  const tables = contracts.map((contract) => {
    const rows = json(resolve(referenceRoot, contract.file));
    const workbook = workbookByFile.get(contract.file);
    if (!workbook) throw new Error(`workbook missing for ${contract.file}`);
    const fields = fieldsForRows(rows);
    return `[[tables]]
name = ${quote(`Gb${pascal(contract.file)}`)}
mode = "map"
key = "id"
[tables.source]
format = "xlsx"
file = ${quote(workbook)}
sheet = ${quote(sheetName(contract.file))}
[[tables.fields]]
name = "id"
type = "i32"
range = [1, 2147483647]
[[tables.fields]]
name = "stable_key"
type = "string"
length = [1, 32767]
${fields.map((field) => `[[tables.fields]]
name = ${quote(field)}
type = "${fieldIsOptional(rows, field) ? "optional<string>" : "string"}"
length = [1, 32767]`).join("\n")}
[[tables.indexes]]
name = "by_stable_key"
fields = ["stable_key"]
unique = true
`;
  }).join("\n");
  return `# @generated by generate-sora-schema.mjs; do not edit.
# ${basename(fileName, ".toml")} workbook partition; reference-only data.

${tables}`;
}
