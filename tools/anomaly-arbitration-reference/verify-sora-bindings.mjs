#!/usr/bin/env node

import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { readFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const root = path.resolve(".");
const projectPath = path.join(
  root,
  "config/anomaly-arbitration/project.toml",
);
const schemaPath = path.join(
  root,
  "config/anomaly-arbitration/schema/bindings.toml",
);
const sora = path.join(
  root,
  ".cache/tools/sora-cli-0.3.0/bin/sora",
);

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

execFileSync(process.execPath, [
  path.join(
    root,
    "tools/anomaly-arbitration-reference/generate-sora-bindings-schema.mjs",
  ),
  "--check",
], { stdio: "inherit" });
const [project, schema] = await Promise.all([
  readFile(projectPath, "utf8"),
  readFile(schemaPath, "utf8"),
]);
execFileSync(sora, ["check", "--project", projectPath], {
  cwd: root,
  stdio: "inherit",
});
assert(project.includes('"schema/bindings.toml"'),
  "bindings schema include drift");
const expected = new Map([
  ["AAPoolAudits", "PoolAudits"],
  ["AATraits", "Traits"],
  ["AAMazeBuffBindings", "MazeBuffBindings"],
  ["AABattleEvents", "BattleEvents"],
  ["AAEncounters", "Encounters"],
  ["AAEncounterWaves", "EncounterWaves"],
  ["AAEnemySlots", "EnemySlots"],
  ["AAEnemies", "Enemies"],
  ["AAEnemySkills", "EnemySkills"],
  ["AAEnemyStatuses", "EnemyStatuses"],
  ["AAAbilityBindings", "AbilityBindings"],
  ["AAMechanicContributions", "MechanicContributions"],
]);
const tableBlocks = schema.split("[[tables]]").slice(1);
assert(tableBlocks.length === expected.size, "bindings table count drift");
for (const block of tableBlocks) {
  const name = /name = "([^"]+)"/u.exec(block)?.[1];
  const sheet = /sheet = "([^"]+)"/u.exec(block)?.[1];
  assert(expected.get(name) === sheet, `${name} sheet contract drift`);
  assert(block.includes('file = "AnomalyArbitrationBindings.xlsx"')
    && block.includes('name = "stable_key"')
    && block.includes('name = "payload_json"')
    && block.includes('name = "runtime_executable"')
    && block.includes('name = "manifest_record_ids"')
    && block.includes('name = "source_ref_ids"'),
  `${name} authoring fields drift`);
}
for (const typedReference of [
  "ref<AAStages.id>",
  "ref<AAEncounters.id>",
  "ref<AAEnemies.id>",
])
  assert(schema.includes(typedReference),
    `missing binding typed reference ${typedReference}`);
assert(schema.startsWith(
  "# Generated by tools/anomaly-arbitration-reference/",
) && (schema.match(/name = "source_numeric_id"/gu) ?? []).length === 5,
"generated/source-locator boundary drift");

console.log(
  "Anomaly Arbitration Sora bindings schema verified: "
    + `12 tables, schema=${createHash("sha256").update(schema).digest("hex")}, `
    + `project=${createHash("sha256").update(project).digest("hex")}.`,
);
