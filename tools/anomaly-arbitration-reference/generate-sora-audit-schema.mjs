#!/usr/bin/env node

import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(".");
const check = process.argv.includes("--check");
const output = path.join(
  root,
  "config/anomaly-arbitration/schema/audit.toml",
);

const definitions = [
  ["AAMechanicRules", "MechanicRules", [
    field("family_id", "string", "length = [1, 200]"),
  ]],
  ["AASources", "Sources", [
    field("source_id", "string", "length = [1, 1000]"),
    field("locator", "string", "length = [1, 1000]"),
  ]],
  ["AAReconciliation", "Reconciliation", [
    field("source_path", "string", "length = [1, 1000]"),
    field("row_locator", "string", "length = [1, 1000]"),
    field("peer_goal_id", "string", "length = [1, 200]"),
  ]],
  ["AACoverage", "Coverage", [
    field("manifest_category", "string", "length = [1, 200]"),
    field("manifest_record_id", "string", "length = [1, 1000]"),
  ]],
  ["AAResearchGaps", "ResearchGaps", [
    field("blocking", "bool"),
    field("owner_batch", "string", "length = [1, 200]"),
  ]],
  ["AAReviewFixtures", "ReviewFixtures", [
    field("family_id", "string", "length = [1, 200]"),
    field(
      "evidence_ref_ids",
      "list<ref<AASources.id>>",
      'parser = { kind = "split", separator = "|" }\nlength = [1, 1024]',
    ),
  ]],
  ["AAManifestReceipt", "ManifestReceipt", [
    field(
      "profile_id",
      "ref<AAProfiles.id>",
    ),
  ]],
  ["AAPackIndex", "PackIndex", [
    field("file_order", "i32", "range = [1, 100]"),
    field("record_order", "i32", "range = [0, 1000000]"),
  ]],
];

function field(name, type, constraint = "") {
  return { name, type, constraint };
}

function renderField({ name, type, constraint }) {
  return [
    "[[tables.fields]]",
    `name = ${JSON.stringify(name)}`,
    `type = ${JSON.stringify(type)}`,
    ...(constraint ? [constraint] : []),
  ].join("\n");
}

const commonFields = [
  field("id", "i32", "range = [1, 2147483647]"),
  field("stable_key", "string", "length = [1, 1200]"),
  field("row_order", "i32", "range = [1, 1000000]"),
  field("name_en", "string", "length = [1, 2200]"),
  field("name_zh_cn", "string", "length = [1, 2200]"),
  field("summary_en", "string", "length = [1, 4000]"),
  field("summary_zh_cn", "string", "length = [1, 4000]"),
  field("ownership", "enum<AAOwnership>"),
  field("coverage_state", "enum<AACoverageState>"),
  field("evidence_quality", "enum<AAEvidenceQuality>"),
  field("mechanism_quality", "enum<AAMechanismQuality>"),
  field(
    "manifest_record_ids",
    "list<string>",
    'parser = { kind = "split", separator = "|" }\nlength = [0, 1024]',
  ),
  field(
    "source_ref_ids",
    "list<string>",
    'parser = { kind = "split", separator = "|" }\nlength = [1, 2048]',
  ),
  field("payload_json", "string", "length = [2, 1000000]"),
  field("runtime_executable", "bool"),
];

const sections = definitions.map(([name, sheet, extraFields]) => [
  "[[tables]]",
  `name = ${JSON.stringify(name)}`,
  'mode = "map"',
  'key = "id"',
  "[tables.source]",
  'format = "xlsx"',
  'file = "AnomalyArbitrationReview.xlsx"',
  `sheet = ${JSON.stringify(sheet)}`,
  ...commonFields.map(renderField),
  ...extraFields.map(renderField),
  "[[tables.indexes]]",
  'name = "by_stable_key"',
  'fields = ["stable_key"]',
  "unique = true",
].join("\n"));
const bytes = [
  "# Generated by tools/anomaly-arbitration-reference/",
  "# generate-sora-audit-schema.mjs; do not hand-edit.",
  "",
  ...sections,
  "",
].join("\n");
await mkdir(path.dirname(output), { recursive: true });
if (check) {
  const existing = await readFile(output, "utf8").catch(() => "");
  if (existing !== bytes) throw new Error("audit.toml generation drift");
} else {
  await writeFile(output, bytes);
}
console.log(`Anomaly Arbitration audit schema generated: ${
  definitions.length
} tables.`);
