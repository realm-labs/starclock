#!/usr/bin/env node

import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(".");
const check = process.argv.includes("--check");
const output = path.join(
  root,
  "config/anomaly-arbitration/schema/bindings.toml",
);

const definitions = [
  ["AAPoolAudits", "PoolAudits", [
    field("pool_family", "string", 'length = [1, 100]'),
  ]],
  ["AATraits", "Traits", [
    field("source_numeric_id", "string", 'length = [1, 64]'),
  ]],
  ["AAMazeBuffBindings", "MazeBuffBindings", [
    field("stage_stable_key", "string", 'length = [1, 200]'),
    field("binding_order", "i32", "range = [1, 1000]"),
  ]],
  ["AABattleEvents", "BattleEvents", [
    field("source_numeric_id", "string", 'length = [1, 64]'),
  ]],
  ["AAEncounters", "Encounters", [
    field(
      "stage_id",
      "ref<AAStages.id>",
    ),
    field("source_stage_id", "string", 'length = [1, 64]'),
  ]],
  ["AAEncounterWaves", "EncounterWaves", [
    field(
      "encounter_id",
      "ref<AAEncounters.id>",
    ),
    field("wave_order", "i32", "range = [1, 100]"),
  ]],
  ["AAEnemySlots", "EnemySlots", [
    field(
      "encounter_id",
      "ref<AAEncounters.id>",
    ),
    field("wave_order", "i32", "range = [1, 100]"),
    field("slot_order", "i32", "range = [1, 100]"),
    field(
      "enemy_id",
      "ref<AAEnemies.id>",
    ),
  ]],
  ["AAEnemies", "Enemies", [
    field("source_numeric_id", "string", 'length = [1, 64]'),
    field("source_template_id", "string", 'length = [1, 64]'),
  ]],
  ["AAEnemySkills", "EnemySkills", [
    field(
      "enemy_id",
      "ref<AAEnemies.id>",
    ),
    field("source_numeric_id", "string", 'length = [1, 64]'),
    field("skill_order", "i32", "range = [1, 1000]"),
  ]],
  ["AAEnemyStatuses", "EnemyStatuses", [
    field("owner_stable_key", "string", 'length = [1, 300]'),
    field("source_numeric_id", "string", 'length = [1, 64]'),
  ]],
  ["AAAbilityBindings", "AbilityBindings", [
    field("owner_stable_key", "string", 'length = [1, 300]'),
    field("binding_order", "i32", "range = [1, 1000]"),
  ]],
  ["AAMechanicContributions", "MechanicContributions", [
    field("scope", "string", 'length = [1, 100]'),
    field("install_order", "i32", "range = [1, 10000]"),
  ]],
];

function field(name, type, constraint = "") {
  return { name, type, constraint };
}

function renderField({ name, type, constraint }) {
  return [
    "[[tables.fields]]",
    `name = ${JSON.stringify(name)}`,
    `type = ${JSON.stringify(type)}`,
    ...(constraint ? [constraint] : []),
  ].join("\n");
}

const commonFields = [
  field("id", "i32", "range = [1, 2147483647]"),
  field("stable_key", "string", "length = [1, 300]"),
  field("row_order", "i32", "range = [1, 100000]"),
  field("name_en", "string", "length = [1, 300]"),
  field("name_zh_cn", "string", "length = [1, 300]"),
  field("summary_en", "string", "length = [1, 2000]"),
  field("summary_zh_cn", "string", "length = [1, 2000]"),
  field("ownership", "enum<AAOwnership>"),
  field("coverage_state", "enum<AACoverageState>"),
  field("evidence_quality", "enum<AAEvidenceQuality>"),
  field("mechanism_quality", "enum<AAMechanismQuality>"),
  field(
    "manifest_record_ids",
    "list<string>",
    'parser = { kind = "split", separator = "|" }\nlength = [0, 256]',
  ),
  field(
    "source_ref_ids",
    "list<string>",
    'parser = { kind = "split", separator = "|" }\nlength = [1, 1024]',
  ),
  field("payload_json", "string", "length = [2, 200000]"),
  field("runtime_executable", "bool"),
];

const sections = definitions.map(([name, sheet, extraFields]) => [
  "[[tables]]",
  `name = ${JSON.stringify(name)}`,
  'mode = "map"',
  'key = "id"',
  "[tables.source]",
  'format = "xlsx"',
  'file = "AnomalyArbitrationBindings.xlsx"',
  `sheet = ${JSON.stringify(sheet)}`,
  ...commonFields.map(renderField),
  ...extraFields.map(renderField),
  "[[tables.indexes]]",
  'name = "by_stable_key"',
  'fields = ["stable_key"]',
  "unique = true",
].join("\n"));
const bytes = [
  "# Generated by tools/anomaly-arbitration-reference/",
  "# generate-sora-bindings-schema.mjs; do not hand-edit.",
  "",
  ...sections,
  "",
].join("\n");
await mkdir(path.dirname(output), { recursive: true });
if (check) {
  const existing = await readFile(output, "utf8").catch(() => "");
  if (existing !== bytes) throw new Error("bindings.toml generation drift");
} else {
  await writeFile(output, bytes);
}
console.log(`Anomaly Arbitration bindings schema generated: ${
  definitions.length
} tables.`);
