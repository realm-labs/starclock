#!/usr/bin/env node

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const check = process.argv.includes("--check");
assert(process.argv.slice(2).every((value) => value === "--check"),
  "usage: generate-content-progress.mjs [--check]");
const manifest = json(
  "content-manifests/standard-universe-mechanics-complete-v1/content-partitions.json",
);
const gate = json("policy/goal07-shared-capability-gate.json");
const receiptRoot = gate.partition_receipt.root;
const rows = [];
let incompleteSeen = false;

for (const partition of manifest.partitions) {
  const relative = `${receiptRoot}/${partition.id}.json`;
  const exists = fs.existsSync(absolute(relative));
  if (!exists) {
    incompleteSeen = true;
    rows.push(progressRow(partition, "Pending", null, null));
    continue;
  }
  assert(!incompleteSeen, `${partition.id}: receipt exists before an earlier partition`);
  const receipt = json(relative);
  assert(receipt.schema_revision === gate.partition_receipt.schema_revision,
    `${partition.id}: unsupported receipt revision`);
  assert(receipt.goal_id === gate.goal_id && receipt.partition_id === partition.id,
    `${partition.id}: receipt identity differs`);
  assert(receipt.state === "Complete", `${partition.id}: receipt is not Complete`);
  rows.push(progressRow(partition, "Complete", relative, sha256(relative)));
}

const completed = rows.filter(({ state }) => state === "Complete").length;
const progress = {
  schema_revision: "starclock.goal07-content-progress.v1",
  goal_id: gate.goal_id,
  generated_on: "2026-07-25",
  result: completed === rows.length ? "complete" : "in-progress",
  total_partitions: rows.length,
  completed_partitions: completed,
  pending_partitions: rows.length - completed,
  next_partition: rows.find(({ state }) => state === "Pending")?.id ?? null,
  rows,
};
const jsonRelative =
  "evidence/standard-universe-mechanics-complete-v1/content-progress.json";
const docRelative =
  "docs/goals/07-standard-universe-mechanics-content-progress.md";
writeOrCheck(jsonRelative, encode(progress));
writeOrCheck(docRelative, render(progress));
console.log(
  `Goal 07 content progress ${check ? "verified" : "generated"} ` +
  `(${completed}/${rows.length}; next ${progress.next_partition ?? "none"}).`,
);

function progressRow(partition, state, receipt, receiptSha256) {
  return {
    id: partition.id,
    ordinal: partition.ordinal,
    milestone: partition.milestone,
    state,
    receipt,
    receipt_sha256: receiptSha256,
  };
}
function render(progress) {
  const lines = [
    "# Goal 07 Content Completion Progress",
    "",
    "This file is generated by `tools/goal07/generate-content-progress.mjs`.",
    "The assignment columns in the expanded ledger remain frozen; only a validated,",
    "ordered partition receipt can move its state from `Pending` to `Complete`.",
    "",
    `Progress: **${progress.completed_partitions}/${progress.total_partitions}**; ` +
      `next: \`${progress.next_partition ?? "None"}\`.`,
    "",
    "| Batch | State | Milestone | Receipt |",
    "|---|---|---|---|",
  ];
  for (const row of progress.rows)
    lines.push(
      `| \`${row.id}\` | \`${row.state}\` | \`${row.milestone}\` | ` +
      `${row.receipt ? `\`${row.receipt}\`` : "—"} |`,
    );
  lines.push("");
  return `${lines.join("\n")}\n`;
}
function writeOrCheck(relative, value) {
  const file = absolute(relative);
  if (check) {
    assert(fs.existsSync(file), `${relative} is missing; generate it first`);
    assert(fs.readFileSync(file, "utf8") === value, `${relative} has generated drift`);
    return;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, value);
}
function absolute(relative) { return path.join(root, relative); }
function json(relative) { return JSON.parse(fs.readFileSync(absolute(relative), "utf8")); }
function sha256(relative) {
  return crypto.createHash("sha256").update(fs.readFileSync(absolute(relative))).digest("hex");
}
function encode(value) { return `${JSON.stringify(value, null, 2)}\n`; }
function assert(condition, message) { if (!condition) throw new Error(message); }
