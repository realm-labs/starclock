#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const args = process.argv.slice(2);
const check = args.includes("--check");
const root = path.resolve(valueAfter("--root")
  ?? path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../.."));
const through = valueAfter("--through") ?? "P3-B1";
const configRoot = path.join(root, "config/currency-wars");
const schemaRoot = path.join(configRoot, "schema");
const projectRelative = "../currency-wars-project.toml";
const legacyProject = path.join(configRoot, "project.toml");
const normalized = json(path.join(
  root,
  "content-manifests/currency-wars-v1/normalized-schema.json",
));
const authoring = json(path.join(
  root,
  "content-manifests/currency-wars-v1/authoring-contract.json",
));

const segments = [
  {
    batch: "P3-B1",
    file: "core.toml",
    phases: ["P1-B1", "P1-B2", "P1-B3"],
  },
  {
    batch: "P3-B2",
    file: "systems.toml",
    phases: ["P1-B4", "P1-B5", "P1-B6", "P1-B7", "P1-B8", "P1-B9"],
  },
  {
    batch: "P3-B3",
    file: "content.toml",
    phases: ["P2-B1", "P2-B2", "P2-B3", "P2-B4", "P2-B5"],
    p2b6Files: ["mechanic-source-files.json", "mechanic-rules.json"],
  },
  {
    batch: "P3-B4",
    file: "audit.toml",
    phases: ["P4-B1"],
    p2b6Files: [
      "sources.json",
      "coverage.json",
      "research-gaps.json",
      "semantic-fixture-families.json",
      "review-fixtures.json",
      "manifest.json",
      "pack-index.json",
    ],
  },
];
const throughIndex = segments.findIndex(({ batch }) => batch === through);
if (throughIndex < 0) throw new Error(`unknown --through ${through}`);
const active = segments.slice(0, throughIndex + 1);
const workbookByFile = new Map(authoring.workbooks.flatMap((workbook) =>
  workbook.normalized_files.map((file) => [file, workbook.file])));

const outputs = new Map();
for (const segment of active) {
  const contracts = normalized.files.filter((contract) =>
    segment.phases.includes(contract.phase)
      || segment.p2b6Files?.includes(contract.file));
  outputs.set(path.join("schema", segment.file),
    renderSegment(segment, contracts));
}
outputs.set(projectRelative, renderProject(active));
writeOutputs(outputs);
console.log(
  `Currency Wars Sora schema ${check ? "verified" : "generated"} through ` +
  `${through}: ${active.reduce((sum, segment) => sum + normalized.files
    .filter((contract) =>
      segment.phases.includes(contract.phase)
        || segment.p2b6Files?.includes(contract.file)).length, 0)} tables.`,
);

function valueAfter(flag) {
  const index = args.indexOf(flag);
  if (index < 0) return undefined;
  if (!args[index + 1] || args[index + 1].startsWith("--"))
    throw new Error(`${flag} requires a value`);
  return args[index + 1];
}
function json(file) {
  return JSON.parse(fs.readFileSync(file, "utf8"));
}
function pascal(value) {
  return value.replace(/\.json$/u, "").split(/[^a-zA-Z0-9]+/u)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");
}
function sheetName(file) {
  return pascal(file).slice(0, 31);
}
function tomlString(value) {
  return JSON.stringify(value);
}
function renderProject(activeSegments) {
  const includes = activeSegments
    .map(({ file }) => `  "currency-wars/schema/${file}",`)
    .join("\n");
  return `# Generated by tools/currency-wars-reference/generate-sora-schema.mjs.
project = { id = "starclock_currency_wars_reference" }
groups = { common = { default = true } }
views = { default = { contract = "starclock_currency_wars_reference/default", groups = ["common"] } }
includes = [
${includes}
]

[build]
default_source_format = "xlsx"
data_root = "currency-wars/data"
view = "default"
schema_lock = "currency-wars-generated/schema.lock"
excel_templates = "currency-wars-generated/templates"

[[build.codegen]]
target = "rust"
out = "currency-wars-generated/rust"
format = "never"

[[build.exports]]
format = "binary"
out = "currency-wars-generated/config.sora"

[[build.exports]]
format = "json-debug"
out = "currency-wars-generated/debug-json"

[codegen.rust]
runtime_format = "sora"
`;
}
function renderSegment(segment, contracts) {
  const tables = contracts.map(renderTable).join("\n");
  return `# Generated by tools/currency-wars-reference/generate-sora-schema.mjs.
# Goal 12 ${segment.batch}; source-shaped authoring rows remain runtime-neutral.

${tables}`;
}
function renderTable(contract) {
  const tableName = `CurrencyWars${pascal(contract.file)}`;
  const tableId = contract.file.replace(/\.json$/u, "");
  const workbook = workbookByFile.get(contract.file);
  if (!workbook) throw new Error(`workbook missing for ${contract.file}`);
  const fields = [
    ["stable_key", 1],
    ["schema_revision", 1],
    ["kind", 1],
    ["name_en", 1],
    ["name_zh_cn", 1],
    ["summary_en", 1],
    ["summary_zh_cn", 1],
    ["ownership", 1],
    ["coverage_state", 1],
    ["evidence_quality", 1],
    ["source_refs_json", 2],
    ["tags_json", 2],
    ...contract.required_domain_fields.map((field) => [field, 0]),
    ...(contract.optional_domain_fields ?? []).map((field) => [field, 0]),
  ];
  const uniqueFields = [...new Map(fields.map((entry) =>
    [entry[0], entry])).values()];
  return `[[tables]]
id = ${tomlString(tableId)}
name = ${tomlString(tableName)}
mode = "map"
key = "id"
[tables.source]
format = "xlsx"
file = ${tomlString(workbook)}
sheet = ${tomlString(sheetName(contract.file))}
[[tables.fields]]
name = "id"
type = "i32"
range = [1, 2147483647]
${uniqueFields.map(([name, minimum]) => `[[tables.fields]]
name = ${tomlString(name)}
type = "${minimum === 0 ? "optional<string>" : "string"}"
length = [1, 32767]`).join("\n")}
[[tables.indexes]]
name = "by_stable_key"
fields = ["stable_key"]
unique = true
`;
}
function writeOutputs(generated) {
  if (check && fs.existsSync(legacyProject))
    throw new Error("obsolete config/currency-wars/project.toml remains");
  if (!check) fs.rmSync(legacyProject, { force: true });
  fs.mkdirSync(schemaRoot, { recursive: true });
  for (const [relative, value] of [...generated.entries()]
    .sort(([left], [right]) => left.localeCompare(right))) {
    const target = path.join(configRoot, relative);
    if (check) {
      if (fs.readFileSync(target, "utf8") !== value)
        throw new Error(`${relative} has generated drift`);
    } else {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, value, "utf8");
    }
  }
}
