#!/usr/bin/env node

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import {
  COMMON_FIELDS,
  rowsForTable,
  tablesThrough,
  workbookFor,
} from "./sora-model.mjs";

const arguments_ = process.argv.slice(2);
const root = resolve(valueAfter("--root") ?? process.cwd());
const batch = valueAfter("--batch") ?? "G19-P3-B1";
const check = arguments_.includes("--check");
const configRoot = resolve(root, "config/fate-star-rail-night");
const tables = tablesThrough(batch);
const byWorkbook = Map.groupBy(tables, ({ workbook }) => workbook);
const outputs = new Map();
for (const [workbook, definitions] of byWorkbook) {
  outputs.set(`schema/${workbook}.toml`, renderSchema(root, definitions));
}
outputs.set("project.toml", renderProject([...byWorkbook.keys()]));

for (const [relative, contents] of outputs) {
  const target = resolve(configRoot, relative);
  if (check) {
    if (!existsSync(target) || readFileSync(target, "utf8") !== contents) {
      throw new Error(`${relative}: generated Sora schema drift`);
    }
  } else {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, contents);
  }
}
console.log(`${check ? "Verified" : "Generated"} ${tables.length} Fate Sora tables through ${batch}.`);

function renderProject(workbooks) {
  return `# @generated by generate-sora-schema.mjs; do not edit.
package = "starclock_fate_star_rail_night_reference"
includes = [
${workbooks.map((name) => `  "schema/${name}.toml",`).join("\n")}
]

[build]
default_source_format = "xlsx"
data_root = "data"
schema_lock = "../fate-star-rail-night-generated/schema.lock"
excel_templates = "../fate-star-rail-night-generated/templates"

[[build.codegen]]
target = "rust"
out = "../fate-star-rail-night-generated/readers/rust"
format = "never"

[[build.exports]]
format = "binary"
out = "../fate-star-rail-night-generated/config.sora"

[[build.exports]]
format = "json-debug"
out = "../fate-star-rail-night-generated/debug-json"

[codegen.rust]
runtime_format = "sora"
`;
}

function renderSchema(root, definitions) {
  return `# @generated by generate-sora-schema.mjs; do not edit.
# Fate/Star Rail Night reference-only workbook partition.

${definitions.map((definition) => renderTable(root, definition)).join("\n")}`;
}

function renderTable(root, definition) {
  const rows = rowsForTable(root, definition);
  if (rows.length === 0) throw new Error(`${definition.sheet}: empty table`);
  const tableName = `Fsn${definition.sheet}`;
  return `[[tables]]
name = ${JSON.stringify(tableName)}
mode = "map"
key = "id"
[tables.source]
format = "xlsx"
file = ${JSON.stringify(workbookFor(definition))}
sheet = ${JSON.stringify(definition.sheet)}
[[tables.fields]]
name = "id"
type = "i32"
range = [1, 2147483647]
${COMMON_FIELDS.map(([name]) => `[[tables.fields]]
name = ${JSON.stringify(name)}
type = "string"
length = [0, 32767]`).join("\n")}
[[tables.indexes]]
name = "by_stable_key"
fields = ["stable_key"]
unique = true
`;
}

function valueAfter(flag) {
  const index = arguments_.indexOf(flag);
  if (index < 0) return undefined;
  if (!arguments_[index + 1] || arguments_[index + 1].startsWith("--")) {
    throw new Error(`${flag} requires a value`);
  }
  return arguments_[index + 1];
}
