function sheetName(file, index) {
  const stem = file.replace(/\.json$/u, "")
    .split("-").map((part) =>
      `${part.slice(0, 1).toUpperCase()}${part.slice(1)}`).join("");
  return `T${String(index + 1).padStart(2, "0")}_${stem}`.slice(0, 31);
}

function string(name, maximum, optional = false) {
  return {
    name,
    type: optional ? "optional<string>" : "string",
    length: optional ? undefined : [1, maximum],
  };
}

function integer(name, minimum, maximum) {
  return { name, type: "i32", range: [minimum, maximum] };
}

function list(name, maximum) {
  return {
    name,
    type: "optional<list<string>>",
    parser: { kind: "split", separator: "|" },
    length: undefined,
    maximum,
  };
}

function typed(name, type, extra = {}) {
  return { name, type, ...extra };
}

function quote(value) {
  return JSON.stringify(value);
}

function toml(value) {
  if (Array.isArray(value)) return `[${value.map(toml).join(", ")}]`;
  if (typeof value === "string") return quote(value);
  if (typeof value === "number" || typeof value === "boolean")
    return String(value);
  return `{ ${Object.entries(value).map(([key, item]) =>
    `${key} = ${toml(item)}`).join(", ")} }`;
}
