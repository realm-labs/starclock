#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const root = path.resolve(
  process.argv[2]
    ?? path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../.."),
);
const manifestRoot = path.join(root, "content-manifests/divergent-universe-v1");
const schemaRoot = path.join(root, "config/divergent-universe/schema");
const projectPath = path.join(root, "config/divergent-universe/project.toml");
const normalized = JSON.parse(fs.readFileSync(
  path.join(manifestRoot, "normalized-schema.json"),
  "utf8",
));
const authoring = JSON.parse(fs.readFileSync(
  path.join(manifestRoot, "authoring-contract.json"),
  "utf8",
));

const groups = [
  {
    file: "core.toml",
    first: "profiles.json",
    last: "arithmetic-mapping-rules.json",
  },
  {
    file: "systems.toml",
    first: "equations.json",
    last: "titan-contributions.json",
  },
  {
    file: "content.toml",
    first: "workbenches.json",
    last: "mechanic-rules.json",
  },
];
const fileOrder = normalized.files.map(({ file }) => file);
const workbookByFile = new Map(authoring.workbooks.flatMap((workbook) =>
  workbook.normalized_files.map((file) => [file, workbook.file])));
const contractByFile = new Map(normalized.files.map((contract) =>
  [contract.file, contract]));
const activeContracts = [];

fs.mkdirSync(schemaRoot, { recursive: true });
for (const group of groups) {
  const first = fileOrder.indexOf(group.first);
  const last = fileOrder.indexOf(group.last);
  if (first < 0 || last < first)
    throw new Error(`invalid schema group ${group.file}`);
  const contracts = fileOrder.slice(first, last + 1).map((file) =>
    contractByFile.get(file));
  activeContracts.push(...contracts);
  fs.writeFileSync(
    path.join(schemaRoot, group.file),
    renderSchema(group.file, contracts),
  );
}
fs.mkdirSync(path.dirname(projectPath), { recursive: true });
fs.writeFileSync(projectPath, renderProject(groups.map(({ file }) => file)));

console.log(
  `Generated Divergent Universe P3-B3 Sora schema ` +
  `(${activeContracts.length} isolated tables).`,
);

function renderProject(schemaFiles) {
  return [
    "# @generated by tools/divergent-universe-reference/generate-sora-schema.mjs",
    "# Do not edit by hand.",
    "",
    'package = "starclock_divergent_universe_reference_config"',
    `includes = ${toml(schemaFiles.map((file) => `schema/${file}`))}`,
    "",
    "[build]",
    'default_source_format = "xlsx"',
    'data_root = "data"',
    'schema_lock = "../divergent-universe-generated/schema.lock"',
    'excel_templates = "../divergent-universe-generated/templates"',
    "",
    "[[build.codegen]]",
    'target = "rust"',
    'out = "../divergent-universe-generated/rust"',
    'format = "never"',
    "",
    "[[build.exports]]",
    'format = "binary"',
    'out = "../divergent-universe-generated/config.sora"',
    "",
    "[[build.exports]]",
    'format = "json-debug"',
    'out = "../divergent-universe-generated/debug-json"',
    "",
    "[codegen.rust]",
    'runtime_format = "sora"',
    "",
  ].join("\n");
}

function renderSchema(filename, contracts) {
  const lines = [
    "# @generated by tools/divergent-universe-reference/generate-sora-schema.mjs",
    "# Do not edit by hand.",
    "",
  ];
  if (filename === "core.toml")
    for (const [name, values] of enums()) lines.push(
      "[[enums]]",
      `name = ${quote(name)}`,
      `values = ${toml(values)}`,
      "",
    );
  for (const [index, contract] of contracts.entries()) {
    const table = contract.record_kind;
    const workbook = workbookByFile.get(contract.file);
    if (!workbook) throw new Error(`missing workbook for ${contract.file}`);
    lines.push(
      "[[tables]]",
      `name = ${quote(table)}`,
      'mode = "map"',
      'key = "id"',
      "[tables.source]",
      'format = "xlsx"',
      `file = ${quote(workbook)}`,
      `sheet = ${quote(sheetName(contract.file, index))}`,
    );
    for (const field of fields(contract))
      lines.push(
        "[[tables.fields]]",
        `name = ${quote(field.name)}`,
        `type = ${quote(field.type)}`,
        ...(field.length ? [`length = ${toml(field.length)}`] : []),
        ...(field.range ? [`range = ${toml(field.range)}`] : []),
        ...(field.parser ? [`parser = ${toml(field.parser)}`] : []),
      );
    lines.push(
      "[[tables.indexes]]",
      'name = "by_stable_key"',
      'fields = ["stable_key"]',
      "unique = true",
      "",
    );
  }
  while (lines.at(-1) === "") lines.pop();
  return `${lines.join("\n")}\n`;
}

function fields(contract) {
  const common = [
    integer("id", 1, 2147483647),
    string("stable_key", 300),
    string("schema_revision", 100),
    string("kind", 160),
    string("name_en", 1000),
    string("name_zh_cn", 1000),
    string("summary_en", 4000),
    string("summary_zh_cn", 4000),
    typed("ownership", "enum<DivergentUniverseOwnership>"),
    typed("coverage_state", "enum<DivergentUniverseCoverageState>"),
    typed("evidence_quality", "enum<DivergentUniverseEvidenceQuality>"),
    list("source_refs", 2048),
    list("tags", 128),
    string("source_id", 300, true),
  ];
  const explicit = referenceFields(contract.file);
  const domains = contract.required_domain_fields
    .filter((name) => name !== "source_id" && !explicit.has(name))
    .map((name) => string(name, 60000, true));
  return [
    ...common,
    ...[...explicit.values()],
    ...domains,
    string("payload_json", 1000000),
  ];
}

